def _utf16_docx(declaration: bool) -> bytes:
    document = (
        '<?xml version="1.0" encoding="UTF-16"?>' + ('<!DOCTYPE w [<!ENTITY x "INJECTED">]>' if declaration else "")
        + '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>'
        + '<w:p><w:r><w:t>hello</w:t></w:r></w:p></w:body></w:document>'
    ).encode("utf-16")
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("[Content_Types].xml", '<?xml version="1.0" encoding="UTF-8"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>')
        archive.writestr("word/document.xml", document)
    return buffer.getvalue()


@pytest.mark.parametrize("declaration", [True, False])
def test_a_utf16_part_cannot_hide_a_doctype(declaration: bool) -> None:
    assert _code(lambda: extract_docx(_utf16_docx(declaration))) == "xml_entities_refused"


def test_a_corrupt_zip_member_is_a_clean_refusal_not_a_crash() -> None:
    good = make_docx()
    # Corrupt the deflated bytes of the first member without touching the archive's directory.
    corrupt = bytearray(good)
    start = corrupt.index(b"[Content_Types].xml") + len("[Content_Types].xml")
    for offset in range(start, start + 20):
        corrupt[offset] ^= 0xFF
    assert sniff(bytes(corrupt)) == "zip"
    assert _code(lambda: check_claim(bytes(corrupt), ".docx")) == "unsupported_format"


def test_unterminated_strings_cannot_make_pdf_parsing_quadratic() -> None:
    import time

    body = b"".join(b"%d 0 obj (unterminated " % index for index in range(1, 2_000)) + b"x" * 200_000
    started = time.monotonic()
    assert _code(lambda: extract_pdf(b"%PDF-1.4\n" + body)) == "malformed_document"
    assert time.monotonic() - started < 2.0
