def test_a_field_instruction_is_skipped_not_evaluated() -> None:
    result = extract_docx(make_docx(field_instruction=True))
    assert result.flags["field_instructions_ignored"] == 1
    assert "INCLUDETEXT" not in result.text


def test_a_doctype_or_entity_is_refused_before_parsing() -> None:
    assert _code(lambda: extract_docx(make_docx(doctype=True))) == "xml_entities_refused"


def test_a_zip_bomb_member_is_refused() -> None:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("[Content_Types].xml", "<Types/>")
        archive.writestr("word/document.xml", b"<w/>" + b" " * (5 * 1024 * 1024))
    assert _code(lambda: extract_docx(buffer.getvalue())) == "archive_bomb"


def test_too_many_members_is_refused() -> None:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_STORED) as archive:
        for index in range(450):
            archive.writestr(f"x/{index}.xml", "<a/>")
    assert _code(lambda: extract_docx(buffer.getvalue())) == "archive_too_large"


def test_a_malformed_docx_is_refused() -> None:
    assert _code(lambda: extract_docx(b"PK\x03\x04 not really a zip")) == "malformed_document"


# ---- text and sniffing -----------------------------------------------------------------------------


def test_text_is_decoded_strictly() -> None:
    assert "Requirements" in extract_text(make_text())
    assert extract_text("\ufeffhello".encode("utf-8")) == "hello"
    assert extract_text("hello".encode("utf-16")) == "hello"
    assert _code(lambda: extract_text(b"\xff\xfe\x00\xd8")) == "unsupported_encoding"
    assert _code(lambda: extract_text(b"caf\xe9 latin-1")) == "unsupported_encoding"


def test_text_is_bounded_by_the_helper() -> None:
    result = extract(("word " * (MAX_TEXT_CHARS // 2)).encode("utf-8"), "txt")
    assert result["truncated"] is True
    assert isinstance(result["text"], str) and len(result["text"]) <= MAX_TEXT_CHARS


@pytest.mark.parametrize(
    ("data", "kind"),
    [
        (b"MZ\x90\x00", "executable"),
        (b"#!/bin/sh\nrm -rf /", "script"),
        (b"@echo off\r\ndel *", "script"),
        (b"L\x00\x00\x00\x01\x14\x02\x00", "shortcut"),
        (b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1", "ole"),
    ],
)
def test_dangerous_bytes_are_recognised_whatever_they_are_called(data: bytes, kind: str) -> None:
    assert sniff(data) == kind
    assert dangerous_kind(kind)
    assert _code(lambda: check_claim(data, ".pdf")) == "unsupported_format"


def test_an_extension_that_disagrees_with_the_bytes_is_refused() -> None:
    assert _code(lambda: check_claim(make_pdf(), ".docx")) == "type_mismatch"
    assert _code(lambda: check_claim(make_text(), ".pdf")) == "type_mismatch"
    assert check_claim(make_pdf(), ".PDF") == "pdf"


def test_the_helper_refuses_a_declared_format_the_bytes_do_not_have() -> None:
    assert _code(lambda: extract(make_pdf(), "docx")) == "type_mismatch"


