@pytest.mark.skipif(sys.platform != "win32", reason="Job Objects are Windows-only")
def test_a_one_process_job_forbids_the_helper_from_starting_anything() -> None:
    from app.services.windows_job import ProcessJob

    job = ProcessJob(max_processes=1)
    try:
        script = "import subprocess,sys\ntry:\n subprocess.run([sys.executable,'-c','0'],check=True)\n print('spawned')\nexcept Exception:\n print('refused')"
        base = helper_command("txt")[0]
        process = subprocess.Popen([base, "-c", "import sys; sys.stdin.read(); " + f"exec({script!r})"], stdin=subprocess.PIPE, stdout=subprocess.PIPE)
        job.assign(process.pid)
        output, _ = process.communicate(b"", timeout=30)
        assert output.strip() == b"refused"
    finally:
        job.close()


